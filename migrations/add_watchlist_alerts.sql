-- Avvisi: disponibilità della watchlist (streaming / noleggio / acquisto)
-- e nuovi episodi andati in onda delle serie seguite

-- Ultima fotografia dei provider per ogni titolo in watchlist
create table if not exists watchlist_availability (
  user_id integer not null references profiles(tmdb_id) on delete cascade,
  media_id integer not null,
  media_type text not null check (media_type in ('movie', 'tv')),
  snapshot jsonb not null default '{"stream":[],"rent":[],"buy":[]}'::jsonb,
  -- provider già segnalati (o presenti alla prima fotografia), per categoria
  notified jsonb not null default '{"stream":[],"rent":[],"buy":[]}'::jsonb,
  checked_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (user_id, media_id, media_type)
);

-- Ultimo episodio andato in onda registrato per ogni serie seguita
-- (last_* null = serie controllata ma senza episodi usciti)
create table if not exists tracked_show_airing (
  user_id integer not null references profiles(tmdb_id) on delete cascade,
  show_id integer not null,
  last_season integer,
  last_episode integer,
  checked_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (user_id, show_id)
);

-- Avvisi mostrati all'utente
create table if not exists watchlist_alerts (
  id bigint generated by default as identity primary key,
  user_id integer not null references profiles(tmdb_id) on delete cascade,
  source text not null default 'availability' check (source in ('availability', 'episode')),
  media_id integer not null,
  media_type text not null check (media_type in ('movie', 'tv')),
  title text not null,
  poster_path text,
  kinds text[] not null default '{}',
  providers jsonb not null default '{}'::jsonb,
  -- solo per source = 'episode': ultimo episodio uscito, quanti nuovi, dove vederlo
  episode jsonb,
  link text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  read_at timestamp with time zone
);

create index if not exists idx_watchlist_alerts_user on watchlist_alerts(user_id, created_at desc);
create index if not exists idx_watchlist_alerts_unread on watchlist_alerts(user_id, media_id, media_type, source) where read_at is null;

-- Accesso solo dal server (service role): nessuna policy per i client
alter table watchlist_availability enable row level security;
alter table watchlist_alerts enable row level security;
alter table tracked_show_airing enable row level security;
